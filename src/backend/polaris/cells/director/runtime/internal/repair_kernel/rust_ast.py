def extract_rust_missing_fields_ast(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic] = (),
) -> RustMissingFieldsAstIndex:
    """Extract Rust missing-field planning facts from provided files only."""

    normalized_base = {
        _normalize_repair_path(path): str(content or "")
        for path, content in dict(base_files or {}).items()
        if _normalize_repair_path(path).endswith(".rs")
    }
    parser = _load_tree_sitter_rust_parser()
    if parser is None:
        return RustMissingFieldsAstIndex(
            structs=(),
            struct_literals=(),
            field_accesses=(),
            diagnostic_targets=tuple(_parse_missing_field_diagnostic_targets(diagnostics)),
            parse_blockers=("rust_tree_sitter_parser_unavailable",),
        )

    structs: list[RustRecordStruct] = []
    struct_literals: list[RustStructLiteral] = []
    field_accesses: list[RustFieldAccess] = []
    parse_blockers: list[str] = []
    for path, content in sorted(normalized_base.items()):
        parsed = _parse_rust_source(parser, content)
        if parsed is None:
            parse_blockers.append(f"rust_tree_sitter_parse_failed:{path}")
            continue
        root_node, source_bytes, line_starts = parsed
        generated_or_marker = _is_generated_or_marker_file(content)
        for node in _walk_tree_sitter_nodes(root_node):
            kind = _node_kind(node)
            if kind == "struct_item":
                struct_item = _parse_record_struct(
                    path=path,
                    source_bytes=source_bytes,
                    line_starts=line_starts,
                    node=node,
                    generated_or_marker_file=generated_or_marker,
                )
                if struct_item is not None:
                    structs.append(struct_item)
                continue
            if kind == "struct_expression":
                literal = _parse_struct_literal(
                    path=path,
                    source_bytes=source_bytes,
                    line_starts=line_starts,
                    node=node,
                    generated_or_marker_file=generated_or_marker,
                )
                if literal is not None:
                    struct_literals.append(literal)
                continue
            if kind == "field_expression":
                access = _parse_field_access(
                    path=path,
                    source_bytes=source_bytes,
                    line_starts=line_starts,
                    node=node,
                    generated_or_marker_file=generated_or_marker,
                )
                if access is not None:
                    field_accesses.append(access)

    targets = tuple(_parse_missing_field_diagnostic_targets(diagnostics))
    diagnostic_field_accesses = tuple(_match_diagnostic_field_accesses(targets, field_accesses))
    return RustMissingFieldsAstIndex(
        structs=tuple(structs),
        struct_literals=tuple(struct_literals),
        field_accesses=tuple(field_accesses),
        diagnostic_targets=targets,
        diagnostic_field_accesses=diagnostic_field_accesses,
        parse_blockers=tuple(parse_blockers),
    )


def plan_rust_missing_fields_shadow(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
) -> RustMissingFieldsShadowPlan:
    """Build read-only candidates/blockers for future Rust missing-field repair."""

    ast_index = extract_rust_missing_fields_ast(base_files=base_files, diagnostics=diagnostics)
    candidates: list[RustMissingFieldsShadowCandidate] = []
    blockers: list[RustMissingFieldsShadowBlocker] = [
        RustMissingFieldsShadowBlocker(
            reason="parse_blocker",
            source_tool="rust_missing_fields_shadow",
            diagnostic_id="",
            message=blocker,
        )
        for blocker in ast_index.parse_blockers
    ]
    structs_by_name: dict[str, list[RustRecordStruct]] = {}
    for struct_item in ast_index.structs:
        structs_by_name.setdefault(struct_item.name, []).append(struct_item)

    file_markers = {
        _normalize_repair_path(path): _is_generated_or_marker_file(str(content or ""))
        for path, content in dict(base_files or {}).items()
    }
    for target in ast_index.diagnostic_targets:
        target_blockers: list[RustMissingFieldsShadowBlocker] = []
        if not target.struct_name:
            target_blockers.append(
                _shadow_blocker(
                    "unknown_type",
                    target,
                    "Rust diagnostic did not expose a concrete struct type.",
                )
            )
            blockers.extend(target_blockers)
            continue

        matching_structs = structs_by_name.get(target.struct_name, [])
        if not matching_structs:
            target_blockers.append(
                _shadow_blocker(
                    "unknown_type",
                    target,
                    f"Struct {target.struct_name} was not found in provided base_files.",
                )
            )
            blockers.extend(target_blockers)
            continue
        if len(matching_structs) > 1:
            target_blockers.append(
                _shadow_blocker(
                    "duplicate_struct",
                    target,
                    f"Struct {target.struct_name} has multiple declarations in provided base_files.",
                    metadata={"paths": tuple(struct_item.path for struct_item in matching_structs)},
                )
            )
            blockers.extend(target_blockers)
            continue

        struct_item = matching_structs[0]
        if target.source_tool == RUST_MISSING_FIELDS_SOURCE_TOOL:
            if not struct_item.generated_or_marker_file:
                target_blockers.append(
                    _shadow_blocker(
                        "non_marker_file",
                        target,
                        "Missing struct field declaration would modify a non-generated/non-marker file.",
                        path=struct_item.path,
                    )
                )
            if struct_item.public_api_visible:
                target_blockers.append(
                    _shadow_blocker(
                        "public_api_expansion_needed",
                        target,
                        "Adding a field to a public struct would expand public API.",
                        path=struct_item.path,
                    )
                )
            if target_blockers:
                blockers.extend(target_blockers)
                continue
            candidates.append(
                RustMissingFieldsShadowCandidate(
                    source_tool=target.source_tool,
                    candidate_kind="missing_struct_field_declaration",
                    diagnostic_id=target.diagnostic_id,
                    path=struct_item.path,
                    struct_name=struct_item.name,
                    field_name=target.field_name,
                    field_type_text=None,
                    field_type_source="not_inferred",
                    generated_or_marker_file=struct_item.generated_or_marker_file,
                    metadata={
                        "target_struct_field_names": tuple(field.name for field in struct_item.fields),
                        "type_guessing_allowed": False,
                    },
                )
            )
            blockers.append(
                _shadow_blocker(
                    "type_inference_required",
                    target,
                    "Rust E0609 does not provide a reliable type for the missing struct field.",
                    path=struct_item.path,
                    metadata={
                        "field_type_source": "not_inferred",
                        "type_guessing_allowed": False,
                        "runtime_executable": False,
                    },
                )
            )
            continue

        if target.source_tool == RUST_STRUCT_LITERAL_MISSING_FIELD_SOURCE_TOOL:
            literal_path = target.path
            if not literal_path or not file_markers.get(literal_path, False):
                target_blockers.append(
                    _shadow_blocker(
                        "non_marker_file",
                        target,
                        "Missing struct literal initializer would modify a non-generated/non-marker file.",
                        path=literal_path,
                    )
                )
            field = next((item for item in struct_item.fields if item.name == target.field_name), None)
            if field is None:
                target_blockers.append(
                    _shadow_blocker(
                        "unknown_struct_field",
                        target,
                        f"Struct {struct_item.name} does not declare field {target.field_name}.",
                        path=struct_item.path,
                    )
                )
            literal = _find_struct_literal_for_target(ast_index.struct_literals, target)
            if literal is None:
                target_blockers.append(
                    _shadow_blocker(
                        "struct_literal_not_found",
                        target,
                        "No matching struct literal was found at the diagnostic location.",
                        path=literal_path,
                    )
                )
            if target_blockers:
                blockers.extend(target_blockers)
                continue
            candidates.append(
                RustMissingFieldsShadowCandidate(
                    source_tool=target.source_tool,
                    candidate_kind="struct_literal_missing_field_initializer",
                    diagnostic_id=target.diagnostic_id,
                    path=str(literal_path),
                    struct_name=struct_item.name,
                    field_name=target.field_name,
                    field_type_text=field.type_text if field is not None else None,
                    field_type_source="record_struct_field",
                    generated_or_marker_file=True,
                    metadata={
                        "initializer_field_names": tuple(item.name for item in literal.fields) if literal else (),
                        "value_guessing_allowed": False,
                    },
                )
            )

    return RustMissingFieldsShadowPlan(
        ast_index=ast_index,
        candidates=tuple(candidates),
        blockers=tuple(blockers),
    )


def build_rust_struct_literal_missing_field_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build a narrow executable plan for generated Rust struct literals only."""

    normalized_base = {
        _normalize_repair_path(path): str(content or "")
        for path, content in dict(base_files or {}).items()
        if _normalize_repair_path(path).endswith(".rs")
    }
    shadow = plan_rust_missing_fields_shadow(base_files=normalized_base, diagnostics=diagnostics)
    if shadow.blockers or len(shadow.candidates) != 1:
        return None

    candidate = shadow.candidates[0]
    if (
        candidate.source_tool != RUST_STRUCT_LITERAL_MISSING_FIELD_SOURCE_TOOL
        or candidate.candidate_kind != "struct_literal_missing_field_initializer"
        or not candidate.generated_or_marker_file
    ):
        return None

    initializer = _safe_rust_missing_field_initializer(candidate.field_type_text)
    if initializer is None:
        return None

    target = next(
        (
            item
            for item in shadow.ast_index.diagnostic_targets
            if item.diagnostic_id == candidate.diagnostic_id
            and item.source_tool == RUST_STRUCT_LITERAL_MISSING_FIELD_SOURCE_TOOL
        ),
        None,
    )
    if target is None:
        return None

    matching_literals = tuple(
        literal
        for literal in shadow.ast_index.struct_literals
        if literal.path == candidate.path
        and literal.struct_name == candidate.struct_name
        and (target.line is None or _line_in_node_span(target.line, literal))
    )
    if len(matching_literals) != 1:
        return None
    literal = matching_literals[0]
    if not literal.generated_or_marker_file or not literal.fields:
        return None
    if any(field.name == candidate.field_name for field in literal.fields):
        return None

    content = normalized_base.get(candidate.path)
    if content is None:
        return None
    operation = _struct_literal_missing_field_operation(
        content=content,
        literal=literal,
        field_name=candidate.field_name,
        initializer=initializer,
        diagnostic_id=candidate.diagnostic_id,
    )
    if operation is None:
        return None

    planned_diagnostic = next(
        (diagnostic for diagnostic in diagnostics if diagnostic.diagnostic_id == candidate.diagnostic_id),
        None,
    )
    if planned_diagnostic is None:
        return None

    return RepairPlan(
        rule_id=RUST_STRUCT_LITERAL_MISSING_FIELD_RULE_ID,
        source_tool=RUST_STRUCT_LITERAL_MISSING_FIELD_SOURCE_TOOL,
        operations=(operation,),
        diagnostics=(planned_diagnostic,),
        mode=mode,
        risk_level="low",
        priority=3,
        metadata={
            "repair_kind": "rust_struct_literal_missing_field_initializer",
            "edit_strategy": "text_replace",
            "span_based": True,
            "generated_or_marker_file_required": True,
            "single_struct_literal_required": True,
            "safe_initializer_source": "field_type_whitelist",
            "diagnostic_count": 1,
        },
    )


def _load_tree_sitter_rust_parser() -> Any | None:
    try:
        module = import_module("tree_sitter_language_pack")
    except ImportError:
        return None
    parser_getter = getattr(module, "get_parser", None)
    if not callable(parser_getter):
        return None
    try:
        return parser_getter("rust")
    except (KeyError, TypeError, ValueError):
        return None


def _parse_rust_source(parser: Any, content: str) -> tuple[Any, bytes, tuple[int, ...]] | None:
    source_text = str(content or "")
    source_bytes = source_text.encode("utf-8")
    tree = None
    try:
        tree = parser.parse(source_text)
    except TypeError:
        try:
            tree = parser.parse(source_bytes)
        except (RuntimeError, ValueError, TypeError):
            return None
    except (RuntimeError, ValueError):
        return None
    root_node = _tree_root_node(tree)
    if root_node is None:
        return None
    return root_node, source_bytes, _line_start_byte_offsets(source_bytes)


def _tree_root_node(tree: Any) -> Any | None:
    value = getattr(tree, "root_node", None)
    if callable(value):
        try:
            return value()
        except (RuntimeError, TypeError, ValueError):
            return None
    return value


def _parse_record_struct(
    *,
    path: str,
    source_bytes: bytes,
    line_starts: tuple[int, ...],
    node: Any,
    generated_or_marker_file: bool,
) -> RustRecordStruct | None:
    children = tuple(_node_children(node))
    name_node = _first_child_with_kind(children, {"type_identifier"})
    field_list = _first_child_with_kind(children, {"field_declaration_list"})
    if name_node is None or field_list is None:
        return None
    name = _node_text(name_node, source_bytes).strip()
    if not name:
        return None
    visibility_node = _first_child_with_kind(children, {"visibility_modifier"})
    visibility = _node_text(visibility_node, source_bytes).strip() if visibility_node is not None else ""
    fields = tuple(
        field
        for field in (
            _parse_record_struct_field(
                path=path,
                struct_name=name,
                source_bytes=source_bytes,
                line_starts=line_starts,
                node=field_node,
            )
            for field_node in _node_children(field_list)
            if _node_kind(field_node) == "field_declaration"
        )
        if field is not None
    )
    line, column = _line_column_for_byte(line_starts, _node_start_byte(node))
    return RustRecordStruct(
        path=path,
        name=name,
        visibility=visibility,
        fields=fields,
        start_byte=_node_start_byte(node),
        end_byte=_node_end_byte(node),
        line=line,
        column=column,
        generated_or_marker_file=generated_or_marker_file,
    )


