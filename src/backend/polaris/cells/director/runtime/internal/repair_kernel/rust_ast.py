def _struct_literal_missing_field_operation(
    *,
    content: str,
    literal: RustStructLiteral,
    field_name: str,
    initializer: str,
    diagnostic_id: str,
) -> RepairOperation | None:
    close_brace_byte = content.encode("utf-8").rfind(b"}", literal.start_byte, literal.end_byte)
    if close_brace_byte < literal.start_byte:
        return None
    close_brace = _char_index_for_byte_offset(content, close_brace_byte)
    if close_brace is None:
        return None

    if literal.line == literal.end_line:
        span_start = close_brace
        while span_start > 0 and content[span_start - 1] in " \t":
            span_start -= 1
        expected = content[span_start:close_brace]
        replacement = f", {field_name}: {initializer}{expected}"
        context = _unique_context_for_text_span(content, span_start, close_brace)
        if context is None:
            return None
        return RepairOperation(
            kind="text_replace",
            path=literal.path,
            span_start=span_start,
            span_end=close_brace,
            expected=expected,
            replacement=replacement,
            before_hash=sha256_text(content),
            metadata={
                "repair_kind": "rust_struct_literal_missing_field_initializer",
                "edit_strategy": "text_replace",
                "span_based": True,
                "expected_context_before": context[0],
                "expected_context_after": context[1],
                "diagnostic_id": diagnostic_id,
                "field_name": field_name,
                "initializer_source": "field_type_whitelist",
            },
        )

    last_field = literal.fields[-1]
    last_field_end = _char_index_for_byte_offset(content, last_field.end_byte)
    if last_field_end is None or last_field_end > close_brace:
        return None
    between_last_field_and_close = content[last_field_end:close_brace]
    if ".." in between_last_field_and_close or "," not in between_last_field_and_close:
        return None

    close_line_start = content.rfind("\n", 0, close_brace) + 1
    closing_indent = content[close_line_start:close_brace]
    if closing_indent.strip():
        return None
    field_line_start = content.rfind("\n", 0, _char_index_for_byte_offset(content, last_field.start_byte) or 0) + 1
    field_indent = content[field_line_start : _char_index_for_byte_offset(content, last_field.start_byte) or field_line_start]
    if field_indent.strip():
        return None
    newline = "\r\n" if "\r\n" in content else "\n"
    replacement = f"{field_indent}{field_name}: {initializer},{newline}"
    context = _unique_context_for_text_span(content, close_line_start, close_line_start)
    if context is None:
        return None
    return RepairOperation(
        kind="text_replace",
        path=literal.path,
        span_start=close_line_start,
        span_end=close_line_start,
        expected="",
        replacement=replacement,
        before_hash=sha256_text(content),
        metadata={
            "repair_kind": "rust_struct_literal_missing_field_initializer",
            "edit_strategy": "text_replace",
            "span_based": True,
            "expected_context_before": context[0],
            "expected_context_after": context[1],
            "diagnostic_id": diagnostic_id,
            "field_name": field_name,
            "initializer_source": "field_type_whitelist",
        },
    )


def _safe_rust_missing_field_initializer(type_text: str | None) -> str | None:
    compact = re.sub(r"\s+", "", str(type_text or ""))
    if not compact:
        return None
    if compact in {"u8", "u16", "u32", "u64", "u128", "usize", "i8", "i16", "i32", "i64", "i128", "isize"}:
        return "0"
    if compact in {"f32", "f64"}:
        return "0.0"
    if compact == "bool":
        return "false"
    if compact == "String":
        return "String::new()"
    if compact.startswith("Option<") and compact.endswith(">"):
        return "None"
    if compact.startswith("Vec<") and compact.endswith(">"):
        return "Vec::new()"
    if compact == "()":
        return "()"
    return None


def _unique_context_for_text_span(content: str, span_start: int, span_end: int) -> tuple[str, str] | None:
    if span_start < 0 or span_end < span_start or span_end > len(content):
        return None
    for radius in (24, 48, 96, 192, 384):
        before_start = max(0, span_start - radius)
        after_end = min(len(content), span_end + radius)
        before = content[before_start:span_start]
        after = content[span_end:after_end]
        probe = f"{before}{content[span_start:span_end]}{after}"
        if probe and content.count(probe) == 1:
            return before, after
    return None


def _char_index_for_byte_offset(content: str, byte_offset: int) -> int | None:
    source_bytes = content.encode("utf-8")
    if byte_offset < 0 or byte_offset > len(source_bytes):
        return None
    try:
        return len(source_bytes[:byte_offset].decode("utf-8"))
    except UnicodeDecodeError:
        return None


def _line_in_node_span(line: int, node: RustStructLiteral) -> bool:
    return node.line <= line <= node.end_line


def _diagnostic_location(diagnostic: RepairDiagnostic, raw: str) -> tuple[str | None, int | None, int | None]:
    path = _normalize_repair_path(str(diagnostic.path or "")) or None
    line = diagnostic.line
    column = diagnostic.column
    if path and line is not None and column is not None:
        return path, line, column
    match = _RUST_LOCATION_RE.search(raw)
    if match is None:
        return path, line, column
    return (
        _normalize_repair_path(match.group("path")) or path,
        _to_int(match.group("line")) or line,
        _to_int(match.group("column")) or column,
    )


def _walk_tree_sitter_nodes(node: Any) -> tuple[Any, ...]:
    nodes: list[Any] = []

    def visit(current: Any) -> None:
        nodes.append(current)
        for child in _node_children(current):
            visit(child)

    visit(node)
    return tuple(nodes)


def _node_children(node: Any) -> tuple[Any, ...]:
    children_attr = getattr(node, "children", None)
    if callable(children_attr):
        try:
            children_value = children_attr()
        except (RuntimeError, TypeError, ValueError):
            children_value = ()
        return tuple(children_value or ())
    if children_attr is not None:
        return tuple(children_attr or ())
    child_count = _callable_or_value(getattr(node, "child_count", 0))
    child_getter = getattr(node, "child", None)
    if not callable(child_getter):
        return ()
    children: list[Any] = []
    for index in range(int(child_count or 0)):
        child = child_getter(index)
        if child is not None:
            children.append(child)
    return tuple(children)


def _node_kind(node: Any) -> str:
    value = getattr(node, "type", None)
    if isinstance(value, str) and value:
        return value
    value = _callable_or_value(getattr(node, "kind", ""))
    return str(value or "")


def _node_start_byte(node: Any) -> int:
    return _node_int_attr(node, "start_byte")


def _node_end_byte(node: Any) -> int:
    return _node_int_attr(node, "end_byte")


def _node_int_attr(node: Any, name: str) -> int:
    value = _callable_or_value(getattr(node, name, 0))
    return int(value or 0)


def _node_text(node: Any | None, source_bytes: bytes) -> str:
    if node is None:
        return ""
    start = _node_start_byte(node)
    end = _node_end_byte(node)
    if start < 0 or end < start or end > len(source_bytes):
        return ""
    return source_bytes[start:end].decode("utf-8")


def _first_child_with_kind(children: Sequence[Any], kinds: set[str]) -> Any | None:
    return next((child for child in children if _node_kind(child) in kinds), None)


def _field_type_text(*, node: Any, source_bytes: bytes) -> str:
    children = tuple(_node_children(node))
    colon = _first_child_with_kind(children, {":"})
    if colon is None:
        return ""
    start = _node_end_byte(colon)
    end = _node_end_byte(node)
    return source_bytes[start:end].decode("utf-8").strip().rstrip(",").strip()


def _field_initializer_value_text(*, node: Any, source_bytes: bytes) -> str:
    children = tuple(_node_children(node))
    colon = _first_child_with_kind(children, {":"})
    if colon is None:
        return ""
    start = _node_end_byte(colon)
    end = _node_end_byte(node)
    return source_bytes[start:end].decode("utf-8").strip().rstrip(",").strip()


def _line_start_byte_offsets(source_bytes: bytes) -> tuple[int, ...]:
    starts = [0]
    for index, byte in enumerate(source_bytes):
        if byte == 10:
            starts.append(index + 1)
    return tuple(starts)


def _line_column_for_byte(line_starts: tuple[int, ...], byte_offset: int) -> tuple[int, int]:
    line_index = max(0, bisect_right(line_starts, max(0, byte_offset)) - 1)
    return line_index + 1, max(0, byte_offset - line_starts[line_index]) + 1


def _callable_or_value(value: Any) -> Any:
    if not callable(value):
        return value
    try:
        return value()
    except (RuntimeError, TypeError, ValueError):
        return None


def _simple_rust_type_name(type_text: str | None) -> str | None:
    text = str(type_text or "").strip()
    if not text:
        return None
    text = text.lstrip("&").removeprefix("mut ").strip()
    identifiers = _RUST_IDENTIFIER_RE.findall(text)
    if not identifiers:
        return None
    for identifier in reversed(identifiers):
        if identifier not in {"crate", "super", "self", "mut"}:
            return identifier
    return identifiers[-1]


def _is_generated_or_marker_file(content: str) -> bool:
    head = str(content or "")[:4096].lower()
    return any(term in head for term in _GENERATED_MARKER_TERMS)


def _normalize_repair_path(path: str) -> str:
    normalized = str(path or "").strip().replace("\\", "/")
    while normalized.startswith("./"):
        normalized = normalized[2:]
    if not normalized or normalized.startswith("/"):
        return ""
    if any(part == ".." for part in normalized.split("/")):
        return ""
    return normalized


def _to_int(value: object) -> int | None:
    try:
        return int(str(value))
    except (TypeError, ValueError):
        return None
