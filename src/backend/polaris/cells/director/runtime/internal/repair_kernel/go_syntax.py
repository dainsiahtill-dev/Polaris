def build_go_dedup_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build conservative intra-file and compiler-proven cross-file dedup repairs."""

    normalized_base_files = _normalize_base_files(base_files)
    operations: list[RepairOperation] = []
    for path in sorted(normalized_base_files):
        if not path.endswith(".go") or path.endswith("_test.go"):
            continue
        operations.extend(_go_intra_file_dedup_operations(path, normalized_base_files[path]))
    operations.extend(
        _go_cross_file_dedup_operations(
            base_files=normalized_base_files,
            diagnostics=diagnostics,
        )
    )
    unique_operations: list[RepairOperation] = []
    seen: set[tuple[str, int | None, int | None]] = set()
    for operation in operations:
        key = (operation.path, operation.span_start, operation.span_end)
        if key in seen:
            continue
        seen.add(key)
        unique_operations.append(operation)
    if not unique_operations:
        return None
    return RepairPlan(
        rule_id="go.intra_file_dedup",
        source_tool=GO_DEDUP_SOURCE_TOOL,
        operations=tuple(unique_operations),
        diagnostics=tuple(diagnostics or ()),
        mode=mode,
        risk_level="medium",
        priority=4,
        depends_on=("go.module_import_path",),
        metadata={
            "repair_kind": "go_declaration_dedup",
            "precision_strategy": "compiler_pair_equivalent_declaration_text_replace",
        },
    )


def build_go_unused_import_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build a span-based plan for Go compiler unused-import diagnostics."""

    normalized_base_files = _normalize_base_files(base_files)
    operations: list[RepairOperation] = []
    planned_diagnostics: list[RepairDiagnostic] = []
    seen_spans: set[tuple[str, int, int]] = set()
    for diagnostic in diagnostics:
        import_path = _go_unused_import_path(diagnostic)
        path = _normalize_repair_path(str(diagnostic.path or ""))
        if not import_path or not path or not path.endswith(".go") or path.endswith("_test.go"):
            continue
        content = normalized_base_files.get(path)
        if content is None:
            continue
        operation = _go_unused_import_operation(
            path=path,
            text=content,
            line_number=diagnostic.line,
            import_path=import_path,
        )
        if operation is None:
            continue
        span_key = (operation.path, int(operation.span_start or 0), int(operation.span_end or 0))
        if span_key in seen_spans:
            continue
        seen_spans.add(span_key)
        operations.append(operation)
        planned_diagnostics.append(diagnostic)

    if not operations:
        return None
    return RepairPlan(
        rule_id="go.unused_import",
        source_tool=GO_UNUSED_IMPORT_SOURCE_TOOL,
        operations=tuple(operations),
        diagnostics=tuple(planned_diagnostics),
        mode=mode,
        risk_level="low",
        priority=2,
        depends_on=("go.module_import_path", "go.bare_local_import", "go.import_subpath"),
        metadata={
            "repair_kind": "go_unused_import",
            "edit_strategy": "text_replace",
            "span_based": True,
            "diagnostic_count": len(planned_diagnostics),
        },
    )


