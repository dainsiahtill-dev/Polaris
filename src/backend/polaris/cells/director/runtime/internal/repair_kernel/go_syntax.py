"""Canonical Go syntax repair rules for Director Runtime."""

from __future__ import annotations

import re
from collections.abc import Callable, Mapping, Sequence

from .contracts import RepairDiagnostic, RepairOperation, RepairPlan, sha256_text

GO_BARE_IMPORT_STRING_SOURCE_TOOL = "deterministic_go_bare_import_string_repair"
GO_BARE_LOCAL_IMPORT_SOURCE_TOOL = "deterministic_go_bare_import_repair"
GO_DEDUP_SOURCE_TOOL = "deterministic_go_dedup_repair"
GO_MODULE_IMPORT_SOURCE_TOOL = "deterministic_go_module_import_repair"
GO_NESTED_IMPORT_SOURCE_TOOL = "deterministic_go_nested_import_repair"
GO_SUBPATH_IMPORT_SOURCE_TOOL = "deterministic_go_subpath_repair"

_GO_MOD_MODULE_RE = re.compile(r"^module\s+(\S+)", re.MULTILINE)
_GO_IMPORT_RE = re.compile(r'"([^"]+)"')
_GO_DECLARATION_LINE_RE = re.compile(
    r"^(?P<indent>\s*)(?P<kind>type|const|var)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\b(?P<body>[^\n]*)$"
)
_GO_GENERATED_MARKER_TERMS = (
    "polaris marker:",
    "polaris generated",
    "generated by polaris",
    "code generated",
    "auto-generated",
    "@generated",
    "do not edit",
)


def repair_go_bare_import_strings_text(text: str) -> str:
    """Repair top-level bare quoted strings that should be Go import statements."""

    lines = str(text or "").split("\n")
    modified = False
    in_import_block = False
    past_package = False

    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("package "):
            past_package = True
            continue
        if stripped == "import (" or stripped.startswith("import ("):
            in_import_block = True
            continue
        if in_import_block:
            if stripped == ")":
                in_import_block = False
            continue
        if stripped.startswith("import "):
            continue
        if (
            past_package
            and stripped
            and stripped.startswith('"')
            and stripped.endswith('"')
            and not line.startswith("\t\t")
            and not line.startswith("    ")
        ):
            lines[index] = f"import {stripped}"
            modified = True

    return "\n".join(lines) if modified else str(text or "")


def repair_go_nested_import_keywords_text(text: str) -> str:
    """Repair ``import "pkg"`` lines nested inside Go import blocks."""

    lines = str(text or "").split("\n")
    modified = False
    in_import_block = False

    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("import (") or stripped == "import (":
            in_import_block = True
            continue
        if in_import_block and stripped == ")":
            in_import_block = False
            continue
        if not in_import_block:
            continue
        match = re.match(r'^(\s+)import\s+"([^"]+)"\s*$', line)
        if match is None:
            continue
        lines[index] = f'{match.group(1)}"{match.group(2)}"'
        modified = True

    return "\n".join(lines) if modified else str(text or "")


def build_go_bare_import_string_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build a canonical plan for Go files with bare import strings."""

    normalized_base_files = {
        _normalize_repair_path(path): str(content or "")
        for path, content in dict(base_files or {}).items()
        if _normalize_repair_path(path)
    }
    operations: list[RepairOperation] = []
    for path in sorted(normalized_base_files):
        if not path.endswith(".go") or path.endswith("_test.go"):
            continue
        original = normalized_base_files[path]
        repaired = repair_go_bare_import_strings_text(original)
        if repaired == original:
            continue
        operations.append(
            RepairOperation(
                kind="write_file",
                path=path,
                content=repaired,
                before_hash=sha256_text(original),
                metadata={"repair_kind": "go_bare_import_string"},
            )
        )
    if not operations:
        return None
    return RepairPlan(
        rule_id="go.bare_import_string",
        source_tool=GO_BARE_IMPORT_STRING_SOURCE_TOOL,
        operations=tuple(operations),
        diagnostics=tuple(diagnostics or ()),
        mode=mode,
        risk_level="low",
        priority=0,
    )


def build_go_nested_import_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build a span-based plan for nested Go import keyword repairs."""

    return _build_go_text_plan(
        base_files=base_files,
        diagnostics=diagnostics,
        source_tool=GO_NESTED_IMPORT_SOURCE_TOOL,
        rule_id="go.nested_import_keyword",
        repair_kind="go_nested_import_keyword",
        priority=1,
        depends_on=("go.bare_import_string",),
        transform=_nested_import_operations,
        mode=mode,
    )


def build_go_bare_local_import_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    mode: str = "commit",
) -> RepairPlan | None:
    """Build a span-based plan for adding module prefixes to local Go imports."""

    normalized_base_files = _normalize_base_files(base_files)
    module = _parse_go_mod_module(normalized_base_files.get("go.mod", ""))
    if not module:
        return None
    package_dirs = _discover_go_package_dirs(normalized_base_files)
    if not package_dirs:
        return None
    return _build_go_text_plan(
        base_files=normalized_base_files,
        diagnostics=diagnostics,
        source_tool=GO_BARE_LOCAL_IMPORT_SOURCE_TOOL,
        rule_id="go.bare_local_import",
        repair_kind="go_bare_local_import",
        priority=2,
        depends_on=("go.nested_import_keyword",),
        transform=lambda path, text: _bare_local_import_operations(
            path,
            text,
            module=module,
            package_dirs=package_dirs,
        ),
        mode=mode,
    )


