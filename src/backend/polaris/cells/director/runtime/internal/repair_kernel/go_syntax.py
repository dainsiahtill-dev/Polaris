def _build_go_text_plan(
    *,
    base_files: Mapping[str, str],
    diagnostics: Sequence[RepairDiagnostic],
    source_tool: str,
    rule_id: str,
    repair_kind: str,
    priority: int,
    depends_on: Sequence[str],
    transform: Callable[[str, str], Sequence[RepairOperation]],
    mode: str,
) -> RepairPlan | None:
    normalized_base_files = _normalize_base_files(base_files)
    operations: list[RepairOperation] = []
    for path in sorted(normalized_base_files):
        if not path.endswith(".go") or path.endswith("_test.go"):
            continue
        operations.extend(transform(path, normalized_base_files[path]))
    if not operations:
        return None
    return RepairPlan(
        rule_id=rule_id,
        source_tool=source_tool,
        operations=tuple(operations),
        diagnostics=tuple(diagnostics or ()),
        mode=mode,
        risk_level="low",
        priority=priority,
        depends_on=tuple(depends_on),
        metadata={"repair_kind": repair_kind, "precision_strategy": "span_context_text_patch"},
    )


def _nested_import_operations(path: str, text: str) -> tuple[RepairOperation, ...]:
    operations: list[RepairOperation] = []
    offset = 0
    in_import_block = False
    for line in str(text or "").splitlines(keepends=True):
        line_body, line_ending = _split_line_ending(line)
        stripped = line_body.strip()
        if stripped.startswith("import (") or stripped == "import (":
            in_import_block = True
        elif in_import_block and stripped == ")":
            in_import_block = False
        elif in_import_block:
            match = re.match(r'^(\s+)import\s+"([^"]+)"\s*$', line_body)
            if match is not None:
                replacement = f'{match.group(1)}"{match.group(2)}"'
                operations.append(
                    _text_replace_operation(
                        path=path,
                        text=text,
                        start=offset,
                        end=offset + len(line_body),
                        expected=line_body,
                        replacement=replacement,
                        repair_kind="go_nested_import_keyword",
                        extra_metadata={"line_ending": line_ending},
                    )
                )
        offset += len(line)
    return tuple(operations)


def _bare_local_import_operations(
    path: str,
    text: str,
    *,
    module: str,
    package_dirs: set[str],
) -> tuple[RepairOperation, ...]:
    operations: list[RepairOperation] = []
    for match in _GO_IMPORT_RE.finditer(str(text or "")):
        imported_path = match.group(1).strip()
        if not imported_path or imported_path.startswith(f"{module}/") or imported_path == module:
            continue
        if "." in imported_path.split("/")[0]:
            continue
        replacement_import = ""
        if imported_path in package_dirs or any(
            imported_path.startswith(directory + "/") for directory in package_dirs
        ):
            replacement_import = f"{module}/{imported_path}"
        elif "/" not in imported_path:
            replacement_import = _module_import_for_package_basename(
                imported_path,
                module=module,
                package_dirs=package_dirs,
            )
        if not replacement_import or replacement_import == imported_path:
            continue
        operations.append(
            _text_replace_operation(
                path=path,
                text=text,
                start=match.start(),
                end=match.end(),
                expected=f'"{imported_path}"',
                replacement=f'"{replacement_import}"',
                repair_kind="go_bare_local_import",
                extra_metadata={"module": module, "before_import": imported_path, "after_import": replacement_import},
            )
        )
    return tuple(operations)


def _subpath_import_operations(
    path: str,
    text: str,
    *,
    module: str,
    package_dirs: set[str],
) -> tuple[RepairOperation, ...]:
    operations: list[RepairOperation] = []
    prefix = f"{module}/"
    for match in _GO_IMPORT_RE.finditer(str(text or "")):
        imported_path = match.group(1).strip()
        if not imported_path.startswith(prefix):
            continue
        subpath = imported_path[len(prefix) :]
        if subpath in package_dirs:
            continue
        replacement_dir = _best_package_suffix(subpath, package_dirs)
        if not replacement_dir:
            continue
        replacement_import = f"{module}/{replacement_dir}"
        if replacement_import == imported_path:
            continue
        operations.append(
            _text_replace_operation(
                path=path,
                text=text,
                start=match.start(),
                end=match.end(),
                expected=f'"{imported_path}"',
                replacement=f'"{replacement_import}"',
                repair_kind="go_import_subpath",
                extra_metadata={"module": module, "before_import": imported_path, "after_import": replacement_import},
            )
        )
    return tuple(operations)


def _module_import_operations(
    path: str,
    text: str,
    *,
    module: str,
    package_dirs: set[str],
) -> tuple[RepairOperation, ...]:
    operations: list[RepairOperation] = []
    for match in _GO_IMPORT_RE.finditer(str(text or "")):
        imported_path = match.group(1).strip()
        if not imported_path or imported_path == module or imported_path.startswith(f"{module}/"):
            continue
        if imported_path.startswith((".", "..")) or "/" not in imported_path:
            continue
        wrong_prefix, suffix = imported_path.split("/", 1)
        if not wrong_prefix or "." in wrong_prefix or suffix not in package_dirs:
            continue
        replacement_import = f"{module}/{suffix}"
        operations.append(
            _text_replace_operation(
                path=path,
                text=text,
                start=match.start(),
                end=match.end(),
                expected=f'"{imported_path}"',
                replacement=f'"{replacement_import}"',
                repair_kind="go_module_import_path",
                extra_metadata={
                    "module": module,
                    "before_import": imported_path,
                    "after_import": replacement_import,
                    "wrong_prefix": wrong_prefix,
                },
            )
        )
    return tuple(operations)


def _go_intra_file_dedup_operations(path: str, text: str) -> tuple[RepairOperation, ...]:
    if not _go_generated_or_marker_file(text):
        return ()

    seen: set[tuple[str, str]] = set()
    operations: list[RepairOperation] = []
    offset = 0
    for line in str(text or "").splitlines(keepends=True):
        line_body, line_ending = _split_line_ending(line)
        match = _GO_DECLARATION_LINE_RE.match(line_body)
        if match is None:
            offset += len(line)
            continue
        key = (match.group("kind"), match.group("name"))
        if key in seen and _go_dedup_line_is_safe(line_body):
            replacement = f"{match.group('indent')}// [dedup-intra] {line_body.strip()}"
            operations.append(
                _text_replace_operation(
                    path=path,
                    text=text,
                    start=offset,
                    end=offset + len(line_body),
                    expected=line_body,
                    replacement=replacement,
                    repair_kind="go_intra_file_dedup",
                    extra_metadata={
                        "line_ending": line_ending,
                        "declaration_kind": key[0],
                        "declaration_name": key[1],
                        "generated_or_marker_file_required": "true",
                    },
                )
            )
        seen.add(key)
        offset += len(line)
    return tuple(operations)


def _go_unused_import_operation(
    *,
    path: str,
    text: str,
    line_number: int | None,
    import_path: str,
) -> RepairOperation | None:
    line_span = _go_import_line_span(text, line_number=line_number, import_path=import_path)
    if line_span is None:
        return None
    line_start, line_end, line = line_span
    if f'"{import_path}"' not in line or _GO_IMPORT_RE.search(line) is None:
        return None

    block_span = _go_import_block_span_for_line(text, line_start=line_start, line_end=line_end)
    if block_span is not None and not _go_import_block_has_remaining_imports(
        text,
        block_start=block_span[0],
        block_end=block_span[1],
        removed_start=line_start,
        removed_end=line_end,
    ):
        start, end = block_span
        expected = text[start:end]
        replacement = ""
    else:
        start, end = line_start, line_end
        expected = line
        replacement = ""

    if not expected or start < 0 or end <= start:
        return None
    return _text_replace_operation(
        path=path,
        text=text,
        start=start,
        end=end,
        expected=expected,
        replacement=replacement,
        repair_kind="go_unused_import",
        extra_metadata={
            "edit_strategy": "text_replace",
            "span_based": "true",
            "line_number": str(line_number or ""),
            "import_path": import_path,
        },
    )


def _go_unused_import_path(diagnostic: RepairDiagnostic) -> str:
    if str(diagnostic.code or "") != "go_compile_error":
        return ""
    message = f"{diagnostic.message}\n{diagnostic.raw}"
    match = _GO_UNUSED_IMPORT_RE.search(message)
    return str(match.group("import_path") or "").strip() if match else ""


def _go_undefined_identifier_name(diagnostic: RepairDiagnostic) -> str:
    metadata = diagnostic.metadata if isinstance(diagnostic.metadata, Mapping) else {}
    if str(metadata.get("diagnostic_kind") or "").strip() == "undefined_identifier":
        identifier = str(metadata.get("identifier") or "").strip()
        if identifier:
            return identifier
    for candidate in (diagnostic.message, diagnostic.raw):
        match = _GO_UNDEFINED_IDENTIFIER_RE.search(str(candidate or ""))
        if match is not None:
            return str(match.group("name") or "").strip()
    return ""


def _is_go_error_string_helper_name(identifier: str) -> bool:
    return str(identifier or "") in _GO_ERROR_STRING_HELPER_NAMES


def _go_error_string_helper_operation(path: str, text: str, *, identifier: str) -> RepairOperation | None:
    if _go_error_string_helper_declared(text, identifier=identifier):
        return None
    if _go_error_string_helper_call_re(identifier).search(text) is None:
        return None
    insert_at = _go_error_string_helper_insert_offset(text)
    if insert_at is None:
        return None
    insertion = _go_error_string_helper_insert_text(text, insert_at=insert_at, identifier=identifier)
    return _text_replace_operation(
        path=path,
        text=text,
        start=insert_at,
        end=insert_at,
        expected="",
        replacement=insertion,
        repair_kind="go_error_string_helper",
        extra_metadata={"identifier": identifier},
    )


def _go_error_string_helper_declared(text: str, *, identifier: str) -> bool:
    escaped = re.escape(identifier)
    return re.search(rf"(?m)^(?:type\s+{escaped}\b|func\s+{escaped}\b)", str(text or "")) is not None


def _go_error_string_helper_call_re(identifier: str) -> re.Pattern[str]:
    escaped = re.escape(identifier)
    return re.compile(rf"(?<![\w.]){escaped}\s*\(\s*(?:\"(?:\\.|[^\"])*\"|`[^`]*`)\s*\)")


def _go_error_string_helper_insert_offset(text: str) -> int | None:
    lines = str(text or "").splitlines(keepends=True)
    offset = 0
    package_end: int | None = None
    import_end: int | None = None
    in_import_block = False
    for line in lines:
        stripped = line.strip()
        line_start = offset
        line_end = offset + len(line)
        top_level = not line.startswith((" ", "\t"))
        if package_end is None:
            if top_level and stripped.startswith("package "):
                package_end = line_end
            offset = line_end
            continue
        if in_import_block:
            if top_level and stripped == ")":
                import_end = line_end
                in_import_block = False
            offset = line_end
            continue
        if top_level and stripped.startswith("import ("):
            in_import_block = True
            import_end = line_end
            offset = line_end
            continue
        if top_level and stripped.startswith("import "):
            import_end = line_end
            offset = line_end
            continue
        if import_end is not None and line_start >= import_end:
            break
        offset = line_end
    anchor = import_end if import_end is not None else package_end
    if anchor is None:
        return None
    return _consume_blank_lines(text, anchor)


def _consume_blank_lines(text: str, offset: int) -> int:
    cursor = int(offset)
    while cursor < len(text):
        next_newline = text.find("\n", cursor)
        if next_newline == -1:
            line = text[cursor:]
            if line.strip():
                return cursor
            return len(text)
        line = text[cursor : next_newline + 1]
        if line.strip():
            return cursor
        cursor = next_newline + 1
    return cursor


def _go_error_string_helper_insert_text(text: str, *, insert_at: int, identifier: str) -> str:
    prefix = "" if insert_at == 0 or str(text or "")[:insert_at].endswith("\n\n") else "\n"
    suffix = "" if str(text or "")[insert_at:].startswith("\n") else "\n"
    return f"{prefix}type {identifier} string\n\nfunc (e {identifier}) Error() string {{ return string(e) }}\n{suffix}"


def _go_import_line_span(
    text: str,
    *,
    line_number: int | None,
    import_path: str,
) -> tuple[int, int, str] | None:
    lines = str(text or "").splitlines(keepends=True)
    if line_number is not None and line_number > 0:
        offset = 0
        for current_line_number, line in enumerate(lines, start=1):
            next_offset = offset + len(line)
            if current_line_number == line_number:
                return (offset, next_offset, line) if f'"{import_path}"' in line else None
            offset = next_offset
        return None

    matches: list[tuple[int, int, str]] = []
    offset = 0
    for line in lines:
        next_offset = offset + len(line)
        if f'"{import_path}"' in line and _GO_IMPORT_RE.search(line) is not None:
            matches.append((offset, next_offset, line))
        offset = next_offset
    if len(matches) != 1:
        return None
    return matches[0]


def _go_import_block_span_for_line(
    text: str,
    *,
    line_start: int,
    line_end: int,
) -> tuple[int, int] | None:
    lines = str(text or "").splitlines(keepends=True)
    spans: list[tuple[int, int, str]] = []
    offset = 0
    for line in lines:
        next_offset = offset + len(line)
        spans.append((offset, next_offset, line))
        offset = next_offset

    line_index = next(
        (index for index, (start, end, _line) in enumerate(spans) if start == line_start and end == line_end),
        None,
    )
    if line_index is None:
        return None

    block_start_index: int | None = None
    for index in range(line_index, -1, -1):
        stripped = spans[index][2].strip()
        if stripped.startswith("import ("):
            block_start_index = index
            break
        if stripped.startswith("package ") or stripped == ")":
            break
    if block_start_index is None:
        return None

    for index in range(block_start_index + 1, len(spans)):
        if spans[index][2].strip() == ")":
            return spans[block_start_index][0], spans[index][1]
    return None


def _go_import_block_has_remaining_imports(
    text: str,
    *,
    block_start: int,
    block_end: int,
    removed_start: int,
    removed_end: int,
) -> bool:
    before = str(text or "")[block_start:removed_start]
    after = str(text or "")[removed_end:block_end]
    return _GO_IMPORT_RE.search(before + after) is not None


def _go_dedup_line_is_safe(line: str) -> bool:
    stripped = str(line or "").strip()
    if not stripped or stripped.startswith("//"):
        return False
    return stripped.count("{") == stripped.count("}") and stripped.count("(") == stripped.count(")")


def _go_generated_or_marker_file(text: str) -> bool:
    lowered = str(text or "").lower()
    return any(term in lowered for term in _GO_GENERATED_MARKER_TERMS)


def _text_replace_operation(
    *,
    path: str,
    text: str,
    start: int,
    end: int,
    expected: str,
    replacement: str,
    repair_kind: str,
    extra_metadata: Mapping[str, str] | None = None,
) -> RepairOperation:
    return RepairOperation(
        kind="text_replace",
        path=path,
        span_start=start,
        span_end=end,
        expected=expected,
        replacement=replacement,
        before_hash=sha256_text(text),
        metadata={
            "repair_kind": repair_kind,
            "precision_strategy": "span_context_text_patch",
            **_unique_context_metadata(text, start, end),
            **dict(extra_metadata or {}),
        },
    )


def _unique_context_metadata(text: str, start: int, end: int) -> dict[str, str]:
    context_before = str(text or "")[max(0, start - 80) : start]
    context_after = str(text or "")[end : min(len(text), end + 80)]
    return {
        "expected_context_before": context_before,
        "expected_context_after": context_after,
        "unique_context": f"{context_before}{str(text or '')[start:end]}{context_after}",
    }


def _parse_go_mod_module(text: str) -> str:
    match = _GO_MOD_MODULE_RE.search(str(text or ""))
    return match.group(1).strip() if match else ""


def _discover_go_package_dirs(base_files: Mapping[str, str]) -> set[str]:
    package_dirs: set[str] = set()
    for path in base_files:
        normalized = _normalize_repair_path(path)
        if not normalized.endswith(".go") or normalized.endswith("_test.go"):
            continue
        directory = normalized.rsplit("/", 1)[0] if "/" in normalized else "."
        if directory == "." or "/." in directory or directory.startswith(".") or "/vendor/" in directory:
            continue
        package_dirs.add(directory)
    return package_dirs


def _module_import_for_package_basename(
    imported_path: str,
    *,
    module: str,
    package_dirs: set[str],
) -> str:
    for directory in sorted(package_dirs):
        if directory.rsplit("/", 1)[-1] == imported_path:
            return f"{module}/{directory}"
    return ""


def _best_package_suffix(subpath: str, package_dirs: set[str]) -> str:
    best = ""
    for directory in package_dirs:
        if (subpath.endswith("/" + directory) or subpath.endswith(directory)) and len(directory) > len(best):
            best = directory
    return best


def _split_line_ending(line: str) -> tuple[str, str]:
    if line.endswith("\r\n"):
        return line[:-2], "\r\n"
    if line.endswith("\n"):
        return line[:-1], "\n"
    return line, ""


def _normalize_base_files(base_files: Mapping[str, str]) -> dict[str, str]:
    return {
        _normalize_repair_path(path): str(content or "")
        for path, content in dict(base_files or {}).items()
        if _normalize_repair_path(path)
    }


def _normalize_repair_path(path: str) -> str:
    normalized = str(path or "").strip().replace("\\", "/")
    while normalized.startswith("./"):
        normalized = normalized[2:]
    if normalized.startswith("/") or normalized.startswith("../") or "/../" in normalized:
        return ""
    return normalized


