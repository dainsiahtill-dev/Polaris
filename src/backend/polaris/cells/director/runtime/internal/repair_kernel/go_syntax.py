def _go_printf_arg_method_operation(
    *,
    path: str,
    text: str,
    arg_name: str,
    method_name: str,
    line_number: int,
) -> RepairOperation | None:
    source = str(text or "")
    lines = source.splitlines(keepends=True)
    if line_number < 1 or line_number > len(lines):
        line_number = next(
            (index for index, item in enumerate(lines, start=1) if arg_name in item and "Printf" in item),
            0,
        )
        if line_number < 1:
            return None
    line = lines[line_number - 1]
    if f"{arg_name}.{method_name}(" in line:
        return None
    pattern = re.compile(rf"(?<![\w.]){re.escape(arg_name)}(?![\w.(])")
    matches = list(pattern.finditer(line))
    if not matches:
        return None
    match = matches[-1]
    line_start = sum(len(item) for item in lines[: line_number - 1])
    start = line_start + match.start()
    end = line_start + match.end()
    return _text_replace_operation(
        path=path,
        text=source,
        start=start,
        end=end,
        expected=arg_name,
        replacement=f"{arg_name}.{method_name}()",
        repair_kind="go_printf_stringer_method",
        extra_metadata={"arg_name": arg_name, "method_name": method_name},
    )


def _go_drop_selector_from_composite_list(*, path: str, text: str, selector: str) -> RepairOperation | None:
    source = str(text or "")
    patterns = (
        rf",\s*{re.escape(selector)}\s*",
        rf"{re.escape(selector)}\s*,\s*",
    )
    for pattern in patterns:
        match = re.search(pattern, source)
        if match is None:
            continue
        return _text_replace_operation(
            path=path,
            text=source,
            start=match.start(),
            end=match.end(),
            expected=match.group(0),
            replacement="",
            repair_kind="go_undefined_selector_alias",
            extra_metadata={"identifier": selector, "replacement": ""},
        )
    return None


def _go_error_string_helper_operation(path: str, text: str, *, identifier: str) -> RepairOperation | None:
    if _go_error_string_helper_declared(text, identifier=identifier):
        return None
    if _go_error_string_helper_call_re(identifier).search(text) is None:
        return None
    insert_at = _go_error_string_helper_insert_offset(text)
    if insert_at is None:
        return None
    insertion = _go_error_string_helper_insert_text(text, insert_at=insert_at, identifier=identifier)
    return _text_replace_operation(
        path=path,
        text=text,
        start=insert_at,
        end=insert_at,
        expected="",
        replacement=insertion,
        repair_kind="go_error_string_helper",
        extra_metadata={"identifier": identifier},
    )


def _go_error_string_helper_declared(text: str, *, identifier: str) -> bool:
    escaped = re.escape(identifier)
    return re.search(rf"(?m)^(?:type\s+{escaped}\b|func\s+{escaped}\b)", str(text or "")) is not None


def _go_error_string_helper_call_re(identifier: str) -> re.Pattern[str]:
    escaped = re.escape(identifier)
    return re.compile(rf"(?<![\w.]){escaped}\s*\(\s*(?:\"(?:\\.|[^\"])*\"|`[^`]*`)\s*\)")


def _go_error_string_helper_insert_offset(text: str) -> int | None:
    lines = str(text or "").splitlines(keepends=True)
    offset = 0
    package_end: int | None = None
    import_end: int | None = None
    in_import_block = False
    for line in lines:
        stripped = line.strip()
        line_start = offset
        line_end = offset + len(line)
        top_level = not line.startswith((" ", "\t"))
        if package_end is None:
            if top_level and stripped.startswith("package "):
                package_end = line_end
            offset = line_end
            continue
        if in_import_block:
            if top_level and stripped == ")":
                import_end = line_end
                in_import_block = False
            offset = line_end
            continue
        if top_level and stripped.startswith("import ("):
            in_import_block = True
            import_end = line_end
            offset = line_end
            continue
        if top_level and stripped.startswith("import "):
            import_end = line_end
            offset = line_end
            continue
        if import_end is not None and line_start >= import_end:
            break
        offset = line_end
    anchor = import_end if import_end is not None else package_end
    if anchor is None:
        return None
    return _consume_blank_lines(text, anchor)


def _consume_blank_lines(text: str, offset: int) -> int:
    cursor = int(offset)
    while cursor < len(text):
        next_newline = text.find("\n", cursor)
        if next_newline == -1:
            line = text[cursor:]
            if line.strip():
                return cursor
            return len(text)
        line = text[cursor : next_newline + 1]
        if line.strip():
            return cursor
        cursor = next_newline + 1
    return cursor


def _go_error_string_helper_insert_text(text: str, *, insert_at: int, identifier: str) -> str:
    prefix = "" if insert_at == 0 or str(text or "")[:insert_at].endswith("\n\n") else "\n"
    suffix = "" if str(text or "")[insert_at:].startswith("\n") else "\n"
    return f"{prefix}type {identifier} string\n\nfunc (e {identifier}) Error() string {{ return string(e) }}\n{suffix}"


def _go_import_line_span(
    text: str,
    *,
    line_number: int | None,
    import_path: str,
) -> tuple[int, int, str] | None:
    lines = str(text or "").splitlines(keepends=True)
    if line_number is not None and line_number > 0:
        offset = 0
        for current_line_number, line in enumerate(lines, start=1):
            next_offset = offset + len(line)
            if current_line_number == line_number:
                return (offset, next_offset, line) if f'"{import_path}"' in line else None
            offset = next_offset
        return None

    matches: list[tuple[int, int, str]] = []
    offset = 0
    for line in lines:
        next_offset = offset + len(line)
        if f'"{import_path}"' in line and _GO_IMPORT_RE.search(line) is not None:
            matches.append((offset, next_offset, line))
        offset = next_offset
    if len(matches) != 1:
        return None
    return matches[0]


def _go_import_block_span_for_line(
    text: str,
    *,
    line_start: int,
    line_end: int,
) -> tuple[int, int] | None:
    lines = str(text or "").splitlines(keepends=True)
    spans: list[tuple[int, int, str]] = []
    offset = 0
    for line in lines:
        next_offset = offset + len(line)
        spans.append((offset, next_offset, line))
        offset = next_offset

    line_index = next(
        (index for index, (start, end, _line) in enumerate(spans) if start == line_start and end == line_end),
        None,
    )
    if line_index is None:
        return None

    block_start_index: int | None = None
    for index in range(line_index, -1, -1):
        stripped = spans[index][2].strip()
        if stripped.startswith("import ("):
            block_start_index = index
            break
        if stripped.startswith("package ") or stripped == ")":
            break
    if block_start_index is None:
        return None

    for index in range(block_start_index + 1, len(spans)):
        if spans[index][2].strip() == ")":
            return spans[block_start_index][0], spans[index][1]
    return None


def _go_import_block_has_remaining_imports(
    text: str,
    *,
    block_start: int,
    block_end: int,
    removed_start: int,
    removed_end: int,
) -> bool:
    before = str(text or "")[block_start:removed_start]
    after = str(text or "")[removed_end:block_end]
    return _GO_IMPORT_RE.search(before + after) is not None


def _go_dedup_line_is_safe(line: str) -> bool:
    stripped = str(line or "").strip()
    if not stripped or stripped.startswith("//"):
        return False
    return stripped.count("{") == stripped.count("}") and stripped.count("(") == stripped.count(")")


def _go_generated_or_marker_file(text: str) -> bool:
    lowered = str(text or "").lower()
    return any(term in lowered for term in _GO_GENERATED_MARKER_TERMS)


def _text_replace_operation(
    *,
    path: str,
    text: str,
    start: int,
    end: int,
    expected: str,
    replacement: str,
    repair_kind: str,
    extra_metadata: Mapping[str, str] | None = None,
) -> RepairOperation:
    return RepairOperation(
        kind="text_replace",
        path=path,
        span_start=start,
        span_end=end,
        expected=expected,
        replacement=replacement,
        before_hash=sha256_text(text),
        metadata={
            "repair_kind": repair_kind,
            "precision_strategy": "span_context_text_patch",
            **_unique_context_metadata(text, start, end),
            **dict(extra_metadata or {}),
        },
    )


def _unique_context_metadata(text: str, start: int, end: int) -> dict[str, str]:
    context_before = str(text or "")[max(0, start - 80) : start]
    context_after = str(text or "")[end : min(len(text), end + 80)]
    return {
        "expected_context_before": context_before,
        "expected_context_after": context_after,
        "unique_context": f"{context_before}{str(text or '')[start:end]}{context_after}",
    }


def _parse_go_mod_module(text: str) -> str:
    match = _GO_MOD_MODULE_RE.search(str(text or ""))
    return match.group(1).strip() if match else ""


def _discover_go_package_dirs(base_files: Mapping[str, str]) -> set[str]:
    package_dirs: set[str] = set()
    for path in base_files:
        normalized = _normalize_repair_path(path)
        if not normalized.endswith(".go") or normalized.endswith("_test.go"):
            continue
        directory = normalized.rsplit("/", 1)[0] if "/" in normalized else "."
        if directory == "." or "/." in directory or directory.startswith(".") or "/vendor/" in directory:
            continue
        package_dirs.add(directory)
    return package_dirs


def _module_import_for_package_basename(
    imported_path: str,
    *,
    module: str,
    package_dirs: set[str],
) -> str:
    for directory in sorted(package_dirs):
        if directory.rsplit("/", 1)[-1] == imported_path:
            return f"{module}/{directory}"
    return ""


def _best_package_suffix(subpath: str, package_dirs: set[str]) -> str:
    best = ""
    for directory in package_dirs:
        if (subpath.endswith("/" + directory) or subpath.endswith(directory)) and len(directory) > len(best):
            best = directory
    return best


def _split_line_ending(line: str) -> tuple[str, str]:
    if line.endswith("\r\n"):
        return line[:-2], "\r\n"
    if line.endswith("\n"):
        return line[:-1], "\n"
    return line, ""


_GO_TEST_ASSERTION_RE = re.compile(
    r"(?:(?P<path>[^:\s]+\.go):(?P<line>\d+):\s+)?"
    r"(?P<func>(?:[A-Za-z_][A-Za-z0-9_]*\.)*[A-Za-z_][A-Za-z0-9_]*)\("
    r"(?P<input>-?[0-9]+(?:\.[0-9]+)?)\s*\)\s*=\s*(?P<actual>\S+)\s*,\s*want\s+(?P<want>\S+)",
    re.IGNORECASE,
)
_GO_CASE_COMPARE_RE = re.compile(
    r"case\s+(?P<ident>[A-Za-z_][A-Za-z0-9_]*)\s*(?P<op><=|<|>=|>)\s*(?P<bound>-?[0-9]+(?:\.[0-9]+)?)\s*:",
)
_GO_CASE_IDENT_RE = re.compile(r"case\s+(?P<ident>[A-Za-z_][A-Za-z0-9_]*)\s*:")
_GO_RETURN_IDENT_RE = re.compile(r"return\s+(?P<ret>[A-Za-z_][A-Za-z0-9_]*)\b")
_GO_RETURN_STRING_RE = re.compile(r'return\s+"(?P<label>[^"]+)"')


def _go_test_assertion_mismatch(diagnostic: RepairDiagnostic) -> tuple[str, str, str, str, str] | None:
    for candidate in (diagnostic.message, diagnostic.raw):
        match = _GO_TEST_ASSERTION_RE.search(str(candidate or ""))
        if match is None:
            continue
        func_name = str(match.group("func") or "").rsplit(".", 1)[-1].strip()
        input_literal = str(match.group("input") or "").strip()
        actual = str(match.group("actual") or "").strip().strip(",")
        want = str(match.group("want") or "").strip().strip(",")
        path = str(match.group("path") or "").strip()
        if func_name and input_literal and actual and want and actual != want:
            return path, func_name, input_literal, actual, want
    return None


def _go_named_func_body(content: str, func_name: str) -> str:
    match = re.search(rf"(?m)^func\s+(?:\([^)]+\)\s+)?{re.escape(func_name)}\s*\(", str(content or ""))
    if match is None:
        return ""
    nxt = re.search(r"(?m)^func\s+", str(content or "")[match.end() :])
    end = match.end() + nxt.start() if nxt is not None else len(content)
    return str(content or "")[match.start() : end]


def _go_const_string_labels(base_files: Mapping[str, str]) -> dict[str, str]:
    labels: dict[str, str] = {}
    for path, text in base_files.items():
        if not path.endswith(".go") or path.endswith("_test.go"):
            continue
        for match in _GO_CASE_IDENT_RE.finditer(str(text or "")):
            ident = str(match.group("ident") or "").strip()
            after = str(text or "")[match.end() : match.end() + 160]
            string_match = _GO_RETURN_STRING_RE.search(after)
            if ident and string_match is not None:
                label = str(string_match.group("label") or "").strip()
                if label:
                    labels[ident] = label
                    labels.setdefault(label, ident)
    return labels


def _go_compare_bands(func_body: str) -> tuple[list[tuple[str, float, str, str]], str]:
    bands: list[tuple[str, float, str, str]] = []
    default_ret = ""
    body = str(func_body or "")
    for match in _GO_CASE_COMPARE_RE.finditer(body):
        after = body[match.end() : match.end() + 160]
        ret_match = _GO_RETURN_IDENT_RE.search(after)
        if ret_match is None:
            continue
        try:
            bound = float(str(match.group("bound") or ""))
        except ValueError:
            continue
        bands.append(
            (
                str(match.group("op") or "").strip(),
                bound,
                str(match.group("bound") or "").strip(),
                str(ret_match.group("ret") or "").strip(),
            )
        )
    default_match = re.search(r"default\s*:", body)
    if default_match is not None:
        ret_match = _GO_RETURN_IDENT_RE.search(body[default_match.end() : default_match.end() + 160])
        if ret_match is not None:
            default_ret = str(ret_match.group("ret") or "").strip()
    return bands, default_ret


def _go_eval_compare_bands(
    value: float,
    bands: Sequence[tuple[str, float, str, str]],
    default_ret: str,
) -> str:
    for op, bound, _bound_text, ret in bands:
        if op == "<" and value < bound:
            return ret
        if op == "<=" and value <= bound:
            return ret
        if op == ">" and value > bound:
            return ret
        if op == ">=" and value >= bound:
            return ret
    return default_ret


def _go_format_float_like(value: float, template: str) -> str:
    if "." in template:
        decimals = len(template.split(".", 1)[1])
        formatted = f"{value:.{decimals}f}"
        if formatted.startswith("0.") and template.startswith("."):
            return formatted[1:]
        return formatted
    if abs(value - round(value)) < 1e-12:
        return f"{round(value):.0f}"
    return f"{value:.2f}"


def _go_candidate_for_want(
    *,
    want_ident: str,
    bands: Sequence[tuple[str, float, str, str]],
    default_ret: str,
    template: str,
) -> str:
    target_index = next((index for index, item in enumerate(bands) if item[3] == want_ident), -1)
    if target_index < 0 and want_ident == default_ret and bands:
        last_op, last_bound, last_text, _last_ret = bands[-1]
        decimals = len(last_text.split(".", 1)[1]) if "." in last_text else 2
        step = 10 ** (-decimals)
        candidate = last_bound + step if last_op in {"<=", ">="} else last_bound
    elif target_index < 0:
        return ""
    else:
        op, bound, bound_text, _ret = bands[target_index]
        decimals = len(bound_text.split(".", 1)[1]) if "." in bound_text else 2
        step = 10 ** (-decimals)
        if op == "<":
            candidate = bound - step
        elif op == "<=":
            candidate = bound
        elif op == ">":
            candidate = bound + step
        else:
            candidate = bound
    if _go_eval_compare_bands(candidate, bands, default_ret) != want_ident:
        return ""
    return _go_format_float_like(candidate, template)


def _go_align_test_input_to_domain_band(
    *,
    test_path: str,
    test_text: str,
    func_name: str,
    input_literal: str,
    want: str,
    base_files: Mapping[str, str],
) -> str | None:
    if not test_path.endswith("_test.go"):
        return None
    leaf = str(func_name or "").rsplit(".", 1)[-1]
    domain_bodies = [
        _go_named_func_body(content, leaf)
        for path, content in base_files.items()
        if path.endswith(".go") and not path.endswith("_test.go") and _go_named_func_body(content, leaf)
    ]
    if len(domain_bodies) != 1:
        return None
    bands, default_ret = _go_compare_bands(domain_bodies[0])
    if not bands and not default_ret:
        return None
    labels = _go_const_string_labels(base_files)
    want_ident = labels.get(want, "")
    if not want_ident:
        suffix = want[:1].upper() + want[1:] if want else ""
        inferred = [ret for _op, _bound, _text, ret in bands if ret.endswith(suffix)]
        if default_ret.endswith(suffix):
            inferred.append(default_ret)
        if len(set(inferred)) == 1:
            want_ident = inferred[0]
    if not want_ident:
        return None
    replacement = _go_candidate_for_want(
        want_ident=want_ident,
        bands=bands,
        default_ret=default_ret,
        template=input_literal,
    )
    if not replacement or replacement == input_literal:
        return None
    existing_literals = {
        token
        for token in re.findall(r"(?<![\d.])(-?[0-9]+(?:\.[0-9]+)?)(?![\d.])", test_text)
        if token != input_literal
    }
    if replacement in existing_literals:
        more_precise = _go_format_float_like(float(replacement), f"{input_literal}0")
        if (
            more_precise in existing_literals
            or _go_eval_compare_bands(float(more_precise), bands, default_ret) != want_ident
        ):
            return None
        replacement = more_precise
    token_re = re.compile(rf"(?<![\d.]){re.escape(input_literal)}(?![\d.])")
    matches = [
        match
        for match in token_re.finditer(test_text)
        if want_ident in test_text[max(0, match.start() - 80) : match.end() + 80]
    ]
    if len(matches) != 1:
        return None
    match = matches[0]
    return f"{test_text[: match.start()]}{replacement}{test_text[match.end() :]}"


def _normalize_base_files(base_files: Mapping[str, str]) -> dict[str, str]:
    return {
        _normalize_repair_path(path): str(content or "")
        for path, content in dict(base_files or {}).items()
        if _normalize_repair_path(path)
    }


def _normalize_repair_path(path: str) -> str:
    normalized = str(path or "").strip().replace("\\", "/")
    while normalized.startswith("./"):
        normalized = normalized[2:]
    if normalized.startswith("/") or normalized.startswith("../") or "/../" in normalized:
        return ""
    return normalized


